/* St. John the Beloved test site: the review page's component → page map (map.js), from the site's own sources: every
   Platform name the site must use (tests/site-coverage.test.js) and the pages whose screens draw it.
   Usage, from the repository root: node docs/briefs/st-john-test-site/build-map.js */
const path = require('path');
const fs = require('fs');
const { execFileSync } = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..', '..');
const site = require(path.join(ROOT, 'tests', 'site.js'));
const titleOf = {};
site.pages().forEach((p) => { if (!titleOf[p.screen]) titleOf[p.screen] = p.title; });
let out = '';
try { out = execFileSync(process.execPath, [path.join(ROOT, 'tests', 'site-coverage.test.js'), '--list'], { encoding: 'utf8' }); } catch (e) { out = e.stdout || ''; }
const rows = out.split('\n').map((l) => /^(\S+)\s+(.+)$/.exec(l)).filter((m) => m && /screens\/|site\.jsx|main\.jsx/.test(m[2])).map((m) => ({
  name: m[1],
  pages: [...new Set(m[2].split(', ').map((f) => { const s = /screens\/([\w-]+)\.jsx/.exec(f); return s ? titleOf[s[1]] || s[1] : 'Every page (the site frame)'; }))].join(', '),
}));
fs.writeFileSync(path.join(__dirname, 'map.js'), '/* GENERATED by build-map.js: the Platform names and the test-site pages that draw them */\nwindow.SITE_MAP = ' + JSON.stringify(rows, null, 0).replace(/\},\{/g, '},\n{') + ';\n');
console.log('map.js: ' + rows.length + ' names');
