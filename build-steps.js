// Plenix · build-steps.js (batch 267; owner: "strictly follow the DS.. no exceptions"): no value is ever passed in a style
// attribute, so a value that depends on the data reaches the stylesheet as an attribute the markup sets, and this file
// writes one rule per allowed step into platform/system/steps.css (generated; never edit it by hand). Each rule only sets
// the component's own custom property, which its stylesheet reads.
//   Tree        the row's level, from aria-level (1..LEVELS)
//   Aspect      [data-plx-aspect] on MediaCard's media and Preview: 4/3, 3/2, 1/1, 16/9
//   Skeleton    [data-plx-width] and [data-plx-height]: every --plx-ref-size-* token, by its name ("200px")
//   Data color  [data-plx-color="<hue>"] on any element: --plx-comp-data-color (solid), -soft and -on-soft, for every
//               --plx-sys-data-color-<hue> in the theme tokens (batch 280)
//   Pane width  [data-plx-width="<size>"] on NavPane, SecondaryPane and SidePanel, and :root[data-plx-panel-<name>-width]
//               for the inspector and filter panels: every --plx-ref-size-* token (batch 281: dragging snaps to them);
//               utils/sizeSteps.js lists them for the splitter
//   ImageEditor the frame's zoom, the picture's filter parts, preset, crop ratio, rotation and flips, a text's font and
//               top, an overlay's opacity and scale: platform/patterns/ImageEditor/image-editor.steps.json (batch 282)
//   DataGrid   a pinned column's data-plx-sticky offset, a tree row's level indent and the grid's data-plx-height, for both
//               the static Table (column widths belong to React)
//   Category    [data-plx-category="<name>"]: the category colors (their own palette, batch 290), as data colors, and the
//               category pill colors (--plx-comp-category-soft, -soft-border, -on-soft; 2026-10-14)
//   TimeGrid    [data-plx-hours] 1..24 and [data-plx-days] 1..7 on the grid; an event's [data-plx-start] and
//               [data-plx-span] in quarter hours (0..95, 1..96)
// Run by build-app.js; node build-steps.js also writes it alone.
const fs = require('fs');
const path = require('path');

const LEVELS = 12;
const ASPECTS = [['4/3', '4 / 3'], ['3/2', '3 / 2'], ['1/1', '1 / 1'], ['16/9', '16 / 9']];

module.exports = function buildSteps(root) {
  const P = path.join(root, 'platform');
  const ref = JSON.parse(fs.readFileSync(path.join(P, 'tokens', 'reference.tokens.json'), 'utf8'))['plx-ref'];
  const sizes = Object.keys(ref).filter((k) => /^size-\d+px$/.test(k)).map((k) => k.replace('size-', ''));
  const out = ['/* Plenix · steps (platform/system/steps.css). GENERATED by build-steps.js: do not edit. A value that depends on the',
    '   data reaches its component as an attribute, and one rule per allowed step sets the component\'s own custom property. */'];
  // tree levels: a row deeper than LEVELS keeps the deepest indent
  out.push('.plx-tree__item>.plx-tree__row{--plx-comp-tree-level:' + (LEVELS - 1) + ';}');
  for (let l = 1; l <= LEVELS; l++) out.push('.plx-tree__item[aria-level="' + l + '"]>.plx-tree__row{--plx-comp-tree-level:' + (l - 1) + ';}');
  // picture shapes
  ASPECTS.forEach(([name, value]) => {
    out.push('.plx-media-card__media[data-plx-aspect="' + name + '"]{--plx-comp-media-card-aspect:' + value + ';}');
    out.push('.plx-preview[data-plx-aspect="' + name + '"]{--plx-comp-preview-aspect:' + value + ';}');
  });
  // skeleton sizes: the size tokens
  sizes.forEach((s) => {
    out.push('.plx-skeleton[data-plx-width="' + s + '"]{--plx-comp-skeleton-inline-size:var(--plx-ref-size-' + s + ');}');
    out.push('.plx-skeleton[data-plx-height="' + s + '"]{--plx-comp-skeleton-block-size:var(--plx-ref-size-' + s + ');}');
  });
  // pane widths: the size tokens (a dragged pane snaps to one)
  sizes.forEach((s) => {
    out.push('.plx-nav-pane[data-plx-width="' + s + '"]{--plx-comp-nav-pane-width:var(--plx-ref-size-' + s + ');}');
    out.push('.plx-secondary-pane[data-plx-width="' + s + '"]{--plx-comp-secondary-pane-width:var(--plx-ref-size-' + s + ');}');
    out.push('.plx-side-panel[data-plx-width="' + s + '"]{--plx-comp-side-panel-width:var(--plx-ref-size-' + s + ');}');
    ['inspector', 'filter'].forEach((p) => out.push(':root[data-plx-panel-' + p + '-width="' + s + '"]{--plx-sys-panel-' + p + '-width:var(--plx-ref-size-' + s + ');}'));
  });
  const bootFile = path.join(P, 'providers', 'theme-boot.js');
  const boot = fs.readFileSync(bootFile, 'utf8');
  const bootNew = boot.replace(/\/\* plx-size-steps \*\/[^/]*\/\* \/plx-size-steps \*\//, '/* plx-size-steps */' + JSON.stringify(sizes.map((s) => parseInt(s, 10)).sort((x, y) => x - y)) + '/* /plx-size-steps */');
  if (bootNew !== boot) fs.writeFileSync(bootFile, bootNew);
  const stepsFile = path.join(P, 'utils', 'sizeSteps.js');
  const stepsText = ['/* Plenix · SIZE_STEPS',
    '   Summary: The size tokens in pixels, GENERATED by build-steps.js from the --plx-ref-size-* tokens (do not edit): the widths a pane snaps to.',
    '   Usage:',
    "     import { SIZE_STEPS, snapSize } from '../../utils/sizeSteps.js';",
    '     snapSize(250, 140, 320)   // 240: the nearest size token within the limits',
    '   Props:',
    '     none: SIZE_STEPS lists the sizes in pixels, smallest first; snapSize(px, min, max) and stepSize(px, dir, min, max)',
    '*/',
    'export const SIZE_STEPS = ' + JSON.stringify(sizes.map((s) => parseInt(s, 10)).sort((a, b) => a - b)) + ';',
    'const within = (min, max) => SIZE_STEPS.filter((s) => s >= min && s <= max);',
    '// the size token nearest to px within [min, max] (the limit itself when no token lies between them)',
    'export function snapSize(px, min, max) { const c = within(min, max); if (!c.length) return Math.max(min, Math.min(max, px)); return c.reduce((a, b) => (Math.abs(b - px) < Math.abs(a - px) ? b : a)); }',
    '// the next size token from px in a direction (+1 wider, -1 narrower), within [min, max]',
    'export function stepSize(px, dir, min, max) { const c = within(min, max); if (!c.length) return px; const cur = snapSize(px, min, max); const i = c.indexOf(cur) + (dir > 0 ? 1 : -1); return c[Math.max(0, Math.min(c.length - 1, i))]; }',
    ''].join('\n');
  if (!fs.existsSync(stepsFile) || fs.readFileSync(stepsFile, 'utf8') !== stepsText) fs.writeFileSync(stepsFile, stepsText);
  // the image editor (batch 282): every value an edit can take, from its steps file
  const E = JSON.parse(fs.readFileSync(path.join(P, 'patterns', 'ImageEditor', 'image-editor.steps.json'), 'utf8'));
  // the page reads the same steps: a module generated from the file (the app build does not load JSON)
  const edFile = path.join(P, 'patterns', 'ImageEditor', 'imageEditorSteps.js');
  const edText = ['/* Plenix · IMAGE_EDITOR_STEPS',
    '   Summary: The steps of the image editor, GENERATED by build-steps.js from image-editor.steps.json (do not edit): presets, crop ratios,',
    '     fonts, slider ranges, the zoom and overlay steps. The picture is drawn from them by system/steps.css.',
    '   Usage:',
    "     import { IMAGE_EDITOR_STEPS } from 'plenix-platform';",
    '   Props:',
    '     none: the steps file as an object',
    '*/',
    'export const IMAGE_EDITOR_STEPS = ' + JSON.stringify(E, null, 2) + ';', ''].join('\n');
  if (!fs.existsSync(edFile) || fs.readFileSync(edFile, 'utf8') !== edText) fs.writeFileSync(edFile, edText);
  const IMG = '.plx-image-editor__image', each = (min, max, step, fn) => { for (let v = min; v <= max; v += step) fn(v); };
  each(E.zoom.min, E.zoom.max, 1, (n) => out.push('.plx-image-editor__frame[data-plx-zoom="' + n + '"]{--plx-comp-image-editor-zoom:' + +Math.pow(E.zoom.base, n).toFixed(4) + ';}'));
  const slider = (k) => E.sliders.find((s) => s.key === k);
  each(slider('brightness').min, slider('brightness').max, E.step, (v) => out.push(IMG + '[data-plx-brightness="' + v + '"]{--plx-comp-image-editor-brightness:' + +(1 + v / 100).toFixed(2) + ';}'));
  each(slider('contrast').min, slider('contrast').max, E.step, (v) => out.push(IMG + '[data-plx-contrast="' + v + '"]{--plx-comp-image-editor-contrast:' + +(1 + v / 100).toFixed(2) + ';}'));
  each(E.saturate.min, E.saturate.max, 1, (v) => out.push(IMG + '[data-plx-saturate="' + v + '"]{--plx-comp-image-editor-saturate:' + +(1 + v / E.saturate.per).toFixed(3) + ';}'));
  each(slider('hueRotation').min, slider('hueRotation').max, E.step, (v) => out.push(IMG + '[data-plx-hue="' + v + '"]{--plx-comp-image-editor-hue:' + v + 'deg;}'));
  each(slider('blur').min, slider('blur').max, 1, (v) => out.push(IMG + '[data-plx-blur="' + v + '"]{--plx-comp-image-editor-blur:' + v + ';}'));
  E.presets.forEach((p) => out.push(IMG + '[data-plx-preset="' + p.id + '"]{--plx-comp-image-editor-preset:' + p.filter + ';}'));
  E.ratios.forEach((r) => out.push(IMG + '[data-plx-ratio="' + r.id + '"]{--plx-comp-image-editor-ratio:' + r.value + ';}'));
  [0, 90, 180, 270].forEach((d) => out.push(IMG + '[data-plx-rotate="' + d + '"]{--plx-comp-image-editor-rotate:' + d + 'deg;}'));
  out.push(IMG + '[data-plx-flip-x]{--plx-comp-image-editor-flip-x:-1;}', IMG + '[data-plx-flip-y]{--plx-comp-image-editor-flip-y:-1;}');
  E.fonts.forEach((f) => out.push('.plx-image-editor__text[data-plx-font="' + f + '"]{--plx-comp-image-editor-text-font:"' + f + '", var(--plx-sys-font-body);}'));
  each(E.textTop.min, E.textTop.max, E.step, (v) => out.push('.plx-image-editor__text[data-plx-top="' + v + '"]{--plx-comp-image-editor-text-top:' + v + '%;}'));
  each(E.overlay.opacity.min, E.overlay.opacity.max, E.step, (v) => out.push('.plx-image-editor__overlay[data-plx-opacity="' + v + '"]{--plx-comp-image-editor-overlay-opacity:' + v / 100 + ';}'));
  each(E.overlay.scale.min, E.overlay.scale.max, E.overlay.scale.step, (v) => out.push('.plx-image-editor__overlay[data-plx-scale="' + v + '"]{--plx-comp-image-editor-overlay-scale:' + v / 100 + ';}'));
  // Static Table offsets and maximum height, from the size tokens; widths belong to the React renderer.
  const gridFiles = [];
  const B = 'plx-table', LEAD = '--plx-comp-data-grid-lead-column-width';
  const g = ['/* Plenix · Table steps. GENERATED by build-steps.js from the size tokens (do not edit): a pinned',
    "   column's offset (data-plx-sticky), the grid's height (data-plx-height). Column widths belong to the React renderer. */"];
  const sticky = (k) => '.' + B + ' .plx-table__grid .plx-table__grid-row .plx-table__grid-cell.plx-table__grid-frozen[data-plx-sticky="' + k + '"],.' + B + ' .plx-table__grid .plx-table__grid-header .plx-table__grid-col.plx-table__grid-frozen[data-plx-sticky="' + k + '"]';
  sizes.forEach((s) => {
    const v = 'var(--plx-ref-size-' + s + ')';
    g.push(sticky(s) + '{inset-inline-start:' + v + ';}');
    g.push(sticky('lead+' + s) + '{inset-inline-start:calc(var(' + LEAD + ') + ' + v + ');}');
    g.push('.' + B + '[data-plx-height="' + s + '"] .plx-table__grid .plx-table__grid-tableholder{max-block-size:' + v + ';}');
  });
  g.push(sticky('lead') + '{inset-inline-start:var(' + LEAD + ');}');
  const gf = path.join(P, 'components', 'Table', 'table-steps.css'), gt = g.join('\n') + '\n';
  if (!fs.existsSync(gf) || fs.readFileSync(gf, 'utf8') !== gt) fs.writeFileSync(gf, gt);
  gridFiles.push(gf);
  // Table's base: the grid's look under Table's own block (plx-table), generated from the grid's stylesheet so the two never
  // drift; a static Table looks like the grid without being one (owner, 2026-10-19: Table is static, DataGrid is the grid)
  const gridCss = fs.readFileSync(path.join(P, 'components', 'DataGrid', 'data-grid.css'), 'utf8').replace(/^\/\*[\s\S]*?\*\/\n/, '');
  const tb = "/* Plenix · Table base. GENERATED by build-steps.js from components/DataGrid/data-grid.css (do not edit): the grid's\n"
    + "   look under Table's own block (plx-table). Table's own rules are in table.css. */\n" + gridCss.split('plx-data-grid').join('plx-table');
  const tf = path.join(P, 'components', 'Table', 'table-base.css');
  if (!fs.existsSync(tf) || fs.readFileSync(tf, 'utf8') !== tb) fs.writeFileSync(tf, tb);
  gridFiles.push(tf);
  // the time grid: its hours and days, and each event's start and length in quarter hours
  for (let h = 1; h <= 24; h++) out.push('.plx-time-grid[data-plx-hours="' + h + '"]{--plx-comp-time-grid-hours:' + h + ';}');
  for (let d = 1; d <= 7; d++) out.push('.plx-time-grid[data-plx-days="' + d + '"]{--plx-comp-time-grid-days:' + d + ';}');
  for (let q = 0; q < 96; q++) out.push('.plx-time-grid__event[data-plx-start="' + q + '"]{--plx-comp-time-grid-start:' + (q / 4) + ';}');
  for (let q = 1; q <= 96; q++) out.push('.plx-time-grid__event[data-plx-span="' + q + '"]{--plx-comp-time-grid-span:' + (q / 4) + ';}');
  // data colors: every hue the theme defines (theme-default.light.tokens.json, --plx-sys-data-color-<hue>)
  const theme = JSON.parse(fs.readFileSync(path.join(P, 'tokens', 'theme-default.light.tokens.json'), 'utf8'))['plx-sys'];
  const hues = Object.keys(theme).map((k) => /^data-color-([a-z]+)$/.exec(k)).filter(Boolean).map((m) => m[1]);
  hues.forEach((h) => out.push('[data-plx-color="' + h + '"]{--plx-comp-data-color:var(--plx-sys-data-color-' + h + ');--plx-comp-data-color-soft:var(--plx-sys-data-color-' + h + '-soft);--plx-comp-data-color-on-soft:var(--plx-sys-data-color-' + h + '-on-soft);}'));
  // the hue names for pickers (ColorSwatch exports DATA_COLORS): generated from the same tokens
  const listFile = path.join(P, 'components', 'ColorSwatch', 'dataColors.js');
  const list = ['/* Plenix · DATA_COLORS',
    '   Summary: The data colors by name, GENERATED by build-steps.js from the --plx-sys-data-color-<hue> theme tokens (do not edit).',
    '   Usage:',
    '     import { DATA_COLORS } from \'plenix-platform\';   // ' + JSON.stringify(hues),
    '     <ColorSwatch color={DATA_COLORS[0]} />',
    '   Props:',
    '     none: a list of hue names, in the order the theme defines them',
    '*/',
    'export const DATA_COLORS = ' + JSON.stringify(hues) + ';', ''].join('\n');
  if (!fs.existsSync(listFile) || fs.readFileSync(listFile, 'utf8') !== list) fs.writeFileSync(listFile, list);
  // category colors (batch 290): their own palette, separate from the theme; [data-plx-category="<name>"] sets the data-color
  // properties (the color as solid and fill, black or white text on it) and the category pill properties (the soft pill of
  // docs/pills-and-colors.md, owner 2026-10-14: --plx-comp-category-soft, -soft-border, -on-soft: shades 100, 300, 700), and
  // categoryColors.js lists them in order
  const cats = Object.keys(theme).filter((k) => !theme[k].$deprecated).map((k) => /^category-([a-z]+)$/.exec(k)).filter(Boolean).map((m) => m[1]);
  const compatibleCats = Object.keys(theme).map((k) => /^category-([a-z]+)$/.exec(k)).filter(Boolean).map((m) => m[1]);
  compatibleCats.forEach((c) => out.push('[data-plx-category="' + c + '"]{--plx-comp-data-color:var(--plx-sys-category-' + c + ');--plx-comp-data-color-soft:var(--plx-sys-category-' + c + ');--plx-comp-data-color-on-soft:var(--plx-sys-category-' + c + '-on);--plx-comp-category-soft:var(--plx-sys-category-' + c + '-soft);--plx-comp-category-soft-border:var(--plx-sys-category-' + c + '-soft-border);--plx-comp-category-on-soft:var(--plx-sys-category-' + c + '-on-soft);}'));
  const catFile = path.join(P, 'components', 'ColorSwatch', 'categoryColors.js');
  const catText = ['/* Plenix · CATEGORY_COLORS',
    '   Summary: The category colors by name, GENERATED by build-steps.js from the --plx-sys-category-<name> tokens (do not edit):',
    '     The 19 active categories in the owner-approved order; deprecated aliases are omitted.',
    '   Usage:',
    "     import { CATEGORY_COLORS } from 'plenix-platform';",
    '     <ColorPicker palette="category" value={category.color} onChange={…} />',
    '   Props:',
    '     none: a list of names',
    '*/',
    'export const CATEGORY_COLORS = ' + JSON.stringify(cats) + ';', ''].join('\n');
  if (!fs.existsSync(catFile) || fs.readFileSync(catFile, 'utf8') !== catText) fs.writeFileSync(catFile, catText);
  const file = path.join(P, 'system', 'steps.css');
  const text = out.join('\n') + '\n';
  const changed = !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text;
  if (changed) fs.writeFileSync(file, text);
  return { file, rules: out.length - 2, changed };
};

if (require.main === module) { const r = module.exports(__dirname); console.log('Wrote platform/system/steps.css (' + r.rules + ' rules' + (r.changed ? '' : ', unchanged') + ')'); }
