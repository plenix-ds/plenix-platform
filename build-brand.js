// Builds the Plenix brand from platform/brand/ (batch 278). Run by build-app.js.
// platform/brand/brand.json names each file of the owner's brand kit (used unedited). This writes:
//   platform/components/Brand/brand.css  the mark as a data: URI mask, so it takes its color from the tokens (currentColor)
//   platform/brand/favicon.svg           the browser icon (a copy of the file brand.json names), linked by every page
// Nothing else names a brand file: to update the brand, replace the files (or edit brand.json) and build.
const fs = require('fs');
const path = require('path');

const dataUri = (svg) => 'url("data:image/svg+xml,' + svg.replace(/\s+/g, ' ').trim()
  .replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E').replace(/"/g, "'") + '")';

module.exports = function buildBrand(root) {
  const dir = path.join(root, 'platform', 'brand');
  const B = JSON.parse(fs.readFileSync(path.join(dir, 'brand.json'), 'utf8'));
  const read = (k) => { const f = path.join(dir, B.files[k]); if (!fs.existsSync(f)) throw new Error('brand file missing: ' + B.files[k]); return fs.readFileSync(f, 'utf8'); };
  const css = [
    '/* Plenix · Brand (platform/components/Brand/brand.css). GENERATED by build-brand.js from platform/brand/ (do not edit by hand).',
    '   The mark (brand.json files.mark) is a mask: it draws in the current text color, so the tokens color it (white on the',
    '   header\'s blue, the accent on a page). Its square includes the kit\'s clear space; the system adds none. */',
    ':root{--plx-comp-brand-mark:' + dataUri(read('mark')) + ';}',
    '.plx-brand-mark{--plx-comp-icon-size:var(--plx-comp-brand-mark-context-size,var(--plx-sys-control-icon-standard));background-color:currentColor;block-size:var(--plx-comp-icon-size);display:inline-block;flex-shrink:0;inline-size:var(--plx-comp-icon-size);mask-image:var(--plx-comp-brand-mark);mask-position:center;mask-repeat:no-repeat;mask-size:contain;}',
    '',
  ].join('\n');
  const out = path.join(root, 'platform', 'components', 'Brand', 'brand.css');
  const fav = path.join(dir, 'favicon.svg');
  const changed = !fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== css;
  if (changed) fs.writeFileSync(out, css);
  const favSvg = read('favicon');
  if (!fs.existsSync(fav) || fs.readFileSync(fav, 'utf8') !== favSvg) fs.writeFileSync(fav, favSvg);
  return { changed, name: B.name };
};
