// Builds the usage index: which Plenix apps use each Platform export (from their `import { … } from 'plenix-platform'`).
//   node build-usage.js      → platform/design-system/usage.js (window.DSUsage); the design system's "Template references"
// Run by npm run build:app and deploy.sh. Generated: edit the apps, never usage.js.
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
// each app (its folder) and the shared suite code; the Asset Manager's sources are under dam/app
const APPS = [['Dashboard', 'dashboard'], ['Projects', 'projects'], ['Messages', 'messages'], ['Contacts', 'contacts'], ['Calendar', 'calendar'],
  ['Tasks', 'tasks'], ['Notes', 'notes'], ['Bookmarks', 'bookmarks'], ['Files', 'files'], ['Settings', 'settings'], ['Asset Manager', 'dam'], ['Suite (shared)', 'suite']];

function sources(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name !== 'node_modules') out.push(...sources(p)); } else if (e.name.endsWith('.jsx')) out.push(p);
  }
  return out;
}

const usage = {};
for (const [app, dir] of APPS) {
  const full = path.join(ROOT, dir);
  if (!fs.existsSync(full)) continue;
  for (const f of sources(full)) {
    const text = fs.readFileSync(f, 'utf8');
    for (const m of text.matchAll(/import\s*\{([^}]*)\}\s*from\s*'plenix-platform'/g)) {
      for (const n of m[1].split(',').map((x) => x.trim().split(/\s+as\s+/)[0]).filter(Boolean)) {
        (usage[n] = usage[n] || []);
        if (usage[n].indexOf(app) < 0) usage[n].push(app);
      }
    }
  }
}
Object.keys(usage).forEach((n) => usage[n].sort());
const sorted = {}; Object.keys(usage).sort().forEach((n) => { sorted[n] = usage[n]; });
const out = path.join(ROOT, 'platform', 'design-system', 'usage.js');
if (!fs.existsSync(path.dirname(out))) { console.log('Skipped usage.js: platform/design-system is not checked out'); process.exit(0); }
const version = require('./package.json').version;
fs.writeFileSync(out, '/* GENERATED by build-usage.js from the apps\' imports and package.json (do not edit): which apps use each Platform export,\n   and the release this source is versioned as. */\nwindow.DSRelease = { version: ' + JSON.stringify(version) + ' };\nwindow.DSUsage = ' + JSON.stringify(sorted, null, 1) + ';\n');
console.log('Built platform/design-system/usage.js (' + Object.keys(sorted).length + ' exports used by the apps)');
