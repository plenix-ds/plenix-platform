// Plenix · the Authentik sign-in page in the Plenix design system (batch 262; owner: "design this using the plenix design
// system"). Writes services/auth/brand.css, the brand's custom CSS (Authentik: System > Brands > authentik-default >
// Custom CSS), with every value read from the Plenix tokens (platform/tokens/tokens.index.json, light and dark at the
// standard density) and DM Sans from the CDN. Run: node services/auth/brand-css.js [version]; apply with ak-brand.py.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const VERSION = process.argv[2] || JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
const CDN = 'https://design-system.lighthouseway.org/cdn/' + VERSION;
const index = JSON.parse(fs.readFileSync(path.join(ROOT, 'platform', 'tokens', 'tokens.index.json'), 'utf8')).tokens;
const byName = new Map(index.map((t) => [t.name, t.resolved]));
const v = (name, mode) => {
  const r = byName.get(name);
  if (!r) throw new Error('no token ' + name);
  const val = r.all !== undefined ? r.all : r[mode + '/standard'];
  if (val === undefined) throw new Error(name + ' has no ' + mode + ' value');
  return val + ' /* ' + name + ' */';
};

// the roles the page uses, per theme
const roles = (mode) => ({
  canvas: v('--plx-sys-surface-canvas', mode),
  card: v('--plx-sys-surface-raised', mode),
  border: v('--plx-sys-border-default', mode),
  field: v('--plx-comp-input-border-color', mode),
  text: v('--plx-sys-content-default', mode),
  muted: v('--plx-sys-content-muted', mode),
  danger: v('--plx-sys-feedback-danger-content', mode),
  header: v('--plx-comp-app-header-surface', mode),
  headerText: v('--plx-comp-app-header-brand', mode),
  scrollbar: v('--plx-sys-scrollbar-thumb', mode),
});
const fixed = {
  font: v('--plx-sys-font-body'),
  primary: v('--plx-sys-action-primary-background'),
  primaryHover: v('--plx-sys-action-primary-background-hover'),
  primaryPressed: v('--plx-sys-action-primary-background-pressed'),
  onPrimary: v('--plx-sys-action-primary-content'),
  focus: v('--plx-sys-focus-ring-color'),
  radius: v('--plx-sys-radius-control', 'light'),
  cardRadius: v('--plx-sys-radius-card-12px'),
  height: v('--plx-sys-control-height-dialog', 'light'),
  borderWidth: v('--plx-comp-input-border-width'),
  semibold: v('--plx-sys-font-weight-semibold'),
  medium: v('--plx-sys-font-weight-medium'),
  bold: v('--plx-sys-font-weight-bold'),
  headerHeight: v('--plx-sys-shell-header-height', 'light'),
  headerInset: v('--plx-sys-space-inset-md', 'light'),
  brandSize: v('--plx-ref-font-size-20'),   // the largest type size in the tokens (owner: "Plenix in the blue header")
  gap: v('--plx-sys-space-layout-xl', 'light'),
};
// the brand (platform/brand/brand.json, batch 278): its name and the kit's mark for a blue background, never named here
const BRAND_DIR = path.join(ROOT, 'platform', 'brand');
const BRAND = JSON.parse(fs.readFileSync(path.join(BRAND_DIR, 'brand.json'), 'utf8'));
const markOnAccent = 'url("data:image/svg+xml,' + fs.readFileSync(path.join(BRAND_DIR, BRAND.files.markOnAccent), 'utf8').replace(/s+/g, ' ').trim()
  .replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E').replace(/"/g, "'") + '")';
fixed.markSize = v('--plx-comp-app-header-icon-size');
fixed.markGap = v('--plx-sys-space-inline-md');
const vars = (r) => Object.keys(r).map((k) => '  --plenix-' + k + ': ' + r[k] + ';').join('\n');

const css = `/* Plenix sign-in (generated by services/auth/brand-css.js from the Plenix tokens, release ${VERSION}; do not edit here) */
@font-face { font-display: swap; font-family: "DM Sans"; font-style: normal; font-weight: 300 700; src: url("${CDN}/fonts/dm-sans-variable-latin.woff2") format("woff2"); }
:root, :host {
${vars(roles('light'))}
${vars(fixed)}
  --pf-global--FontFamily--sans-serif: var(--plenix-font);
  --pf-global--FontFamily--heading--sans-serif: var(--plenix-font);
  --pf-global--FontFamily--text--sans-serif: var(--plenix-font);
  --pf-global--primary-color--100: var(--plenix-primary);
  --pf-global--primary-color--200: var(--plenix-primary-hover);
  --pf-global--link--Color: var(--plenix-primary);
  --pf-global--link--Color--hover: var(--plenix-primary-hover);
}
@media (prefers-color-scheme: dark) {
  :root, :host {
${vars(roles('dark')).replace(/^/gm, '  ')}
  }
}
/* the page: the canvas, no photo, no authentik logo or footer */
.pf-c-background-image, .pf-c-login__main-header.pf-c-brand, .ak-brand, ak-brand-links, .pf-c-login__footer { display: none !important; }
html, body, .pf-c-login, .pf-c-page, .pf-c-drawer__body, .pf-c-drawer__content, .pf-c-drawer__main { background: var(--plenix-canvas) !important; }
:host, body { font-family: var(--plenix-font) !important; color: var(--plenix-text); }
/* the Plenix header: the application header's blue bar with the brand in the largest type size */
.pf-c-login::before { content: ${JSON.stringify(BRAND.name)}; position: fixed; inset-block-start: 0; inset-inline: 0; z-index: 1; display: flex; align-items: center; box-sizing: border-box; block-size: var(--plenix-header-height); padding-inline: var(--plenix-header-inset); background: var(--plenix-header); color: var(--plenix-header-text); font-family: var(--plenix-font); font-size: var(--plenix-brand-size); font-weight: var(--plenix-bold); }
/* the brand mark before the name (brand.json files.markOnAccent: the kit's mark for a blue background), at the header's icon size */
.pf-c-login::before { background-image: ${markOnAccent}; background-repeat: no-repeat; background-size: var(--plenix-mark-size) var(--plenix-mark-size); background-position: var(--plenix-header-inset) center; padding-inline-start: calc(var(--plenix-header-inset) + var(--plenix-mark-size) + var(--plenix-mark-gap)); }
/* the card in the middle of the window, across and down: the same room above and below (the header's height plus the gap),
   so the header never covers it and its center is the window's */
.pf-c-login { box-sizing: border-box !important; display: flex !important; align-items: center !important; justify-content: center !important; min-block-size: 100vh !important; block-size: auto !important; padding-block: calc(var(--plenix-header-height) + var(--plenix-gap)) !important; padding-inline: var(--plenix-header-inset) !important; }
.ak-login-container { margin: 0 auto !important; }
/* Authentik's stacked layout pushes the card down with its own top margin; the page centers it instead */
.pf-c-login__main { margin-block: 0 !important; }
/* Authentik sets the card's container to the window height less its own padding; under the header that is taller than
   the page, so it takes its content's height */
.ak-login-container { block-size: auto !important; min-block-size: 0 !important; }
/* no scrollbar unless the page is taller than the window (the header's padding sits inside the page's height); when one
   shows, it is the Plenix thumb, not Authentik's accent */
html, body, .pf-c-drawer__body, .pf-c-drawer__content, .pf-c-page__main { overflow-x: hidden !important; }
* { scrollbar-color: var(--plenix-scrollbar) transparent !important; scrollbar-width: thin; }
::-webkit-scrollbar-thumb { background-color: var(--plenix-scrollbar) !important; }
::-webkit-scrollbar-track { background: transparent !important; }
/* the card: a raised surface with the default border and the card radius */
.pf-c-login__main { background: var(--plenix-card) !important; border: var(--plenix-border-width) solid var(--plenix-border); border-radius: var(--plenix-card-radius); box-shadow: none !important; }
.pf-c-title, .pf-c-login__main-header h1 { color: var(--plenix-text); font-family: var(--plenix-font) !important; font-weight: var(--plenix-semibold) !important; }
.pf-c-form__label, .pf-c-form__label-text { color: var(--plenix-text); font-weight: var(--plenix-medium) !important; }
.pf-c-form__helper-text, .pf-c-login__main-body p, .pf-c-login__main-footer-band { color: var(--plenix-muted); }
.pf-c-form__helper-text.pf-m-error, .pf-c-form__label-required { color: var(--plenix-danger) !important; }
/* fields: one border; focus changes only its color (no ring) */
.pf-c-form-control { background: var(--plenix-card) !important; border: var(--plenix-border-width) solid var(--plenix-field) !important; border-radius: var(--plenix-radius) !important; color: var(--plenix-text); font-family: var(--plenix-font) !important; min-height: var(--plenix-height); outline: none !important; box-shadow: none !important; }
.pf-c-form-control::after, .pf-c-form-control::before { display: none !important; }
.pf-c-form-control:focus, .pf-c-form-control:focus-within { border-color: var(--plenix-focus) !important; }
.pf-c-form-control[aria-invalid="true"] { border-color: var(--plenix-danger) !important; }
/* the primary button */
.pf-c-button { border-radius: var(--plenix-radius) !important; font-family: var(--plenix-font) !important; font-weight: var(--plenix-semibold); min-height: var(--plenix-height); }
.pf-c-button.pf-m-primary { background: var(--plenix-primary) !important; color: var(--plenix-on-primary) !important; }
.pf-c-button.pf-m-primary:hover { background: var(--plenix-primary-hover) !important; }
.pf-c-button.pf-m-primary:active { background: var(--plenix-primary-pressed) !important; }
.pf-c-button.pf-m-primary::after { display: none !important; }
`;
// custom properties take names, not the camelCase keys
const out = css.replace(/--plenix-([a-zA-Z]+)/g, (m, k) => '--plenix-' + k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()));
fs.writeFileSync(path.join(__dirname, 'brand.css'), out);
console.log('Wrote services/auth/brand.css (' + out.length + ' characters, release ' + VERSION + ')');
