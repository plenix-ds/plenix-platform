// Plenix · build-exports.js (library plan, wave 0): the library lanes' public exports and stylesheets, flattened. Each lane
// owns platform/exports/wNNL.js and wNNL.css (NN = wave, L = lane A/B/C), so no two writers edit platform/index.js or
// platform/platform.css at the same time:
//   exports/wNNL.js    export { Link } from '../components/Link/Link.jsx';        (one export statement per line)
//   exports/wNNL.css   @import url("../components/Link/link.css");               (one import per line)
// This script rewrites ONE generated block in platform/index.js and ONE in platform/platform.css, between
//   /* BEGIN library parts (generated by build-exports.js) */  and  /* END library parts */
// as flat lines in file-name order (paths made relative to platform/), so the build (export names), spec.js (the CSS a
// page reads from platform.css's imports), check-system (every stylesheet imported) and build-packages read them as any
// other export. The hand-written exports above the block are never touched. A line that is not an export or an import,
// a name exported twice or a stylesheet imported twice stops it. Deterministic; run by build-app.js before the bundles.
// Alone: node build-exports.js          node build-exports.js --check   (exits 1 when a block is not current)
const fs = require('fs');
const path = require('path');

const BEGIN = '/* BEGIN library parts (generated by build-exports.js from platform/exports/; edit those files, never this block) */';
const END = '/* END library parts */';
const NAME = /^w(?:\d{2}[A-Z]|DTN)\.(js|css)$/;

// the text with its block replaced (the block is added at `where` when it is not there yet)
function withBlock(text, lines, where) {
  const block = BEGIN + '\n' + lines.map((l) => l + '\n').join('') + END;
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  if (a >= 0 && b > a) return text.slice(0, a) + block + text.slice(b + END.length);
  return where(text, block);
}

module.exports = function buildExports(root, { check = false } = {}) {
  const P = path.join(root, 'platform');
  const DIR = path.join(P, 'exports');
  const files = fs.existsSync(DIR) ? fs.readdirSync(DIR).filter((f) => !f.startsWith('.') && f !== 'README.md').sort() : [];
  const bad = [];
  files.filter((f) => !NAME.test(f)).forEach((f) => bad.push('exports/' + f + ': not a part name (wNNL.js or wNNL.css)'));
  const js = [], css = [];
  for (const f of files.filter((x) => NAME.test(x))) {
    const lines = fs.readFileSync(path.join(DIR, f), 'utf8').replace(/\r\n/g, '\n').split('\n').map((l) => l.trim()).filter((l) => l && !/^(\/\/|\/\*.*\*\/$)/.test(l));
    for (const l of lines) {
      if (f.endsWith('.js')) {
        const m = l.match(/^export \{([^}]+)\} from '\.\.\/((?:components|patterns|providers|hooks|utils|templates|system|charts)\/[^']+)';$/);
        if (!m) { bad.push('exports/' + f + ': "' + l + '" is not export { Name } from \'../<folder>/<file>\';'); continue; }
        if (!fs.existsSync(path.join(P, m[2]))) bad.push('exports/' + f + ': ' + m[2] + ' does not exist');
        js.push({ f, line: 'export {' + m[1] + '} from \'./' + m[2] + '\';', names: m[1].split(',').map((x) => x.trim().split(/\s+as\s+/).pop()).filter(Boolean) });
      } else {
        const m = l.match(/^@import url\("\.\.\/((?:components|patterns|templates|system|charts)\/[^"]+\.css)"\);$/);
        if (!m) { bad.push('exports/' + f + ': "' + l + '" is not @import url("../<folder>/<file>.css");'); continue; }
        if (!fs.existsSync(path.join(P, m[1]))) bad.push('exports/' + f + ': ' + m[1] + ' does not exist');
        css.push({ f, line: '@import url("' + m[1] + '");', file: m[1] });
      }
    }
  }
  const indexFile = path.join(P, 'index.js'), cssFile = path.join(P, 'platform.css');
  const index = fs.readFileSync(indexFile, 'utf8'), sheet = fs.readFileSync(cssFile, 'utf8');
  // names and stylesheets already public outside the block, and twice inside it
  const outside = (t) => { const a = t.indexOf(BEGIN), b = t.indexOf(END); return a >= 0 && b > a ? t.slice(0, a) + t.slice(b + END.length) : t; };
  const handNames = new Set();
  for (const m of outside(index).matchAll(/export\s*\{([^}]*)\}/g)) m[1].split(',').map((s) => s.trim().split(/\s+as\s+/).pop()).filter(Boolean).forEach((n) => handNames.add(n));
  const seen = {};
  js.forEach((x) => x.names.forEach((n) => { if (handNames.has(n)) bad.push('exports/' + x.f + ': ' + n + ' is already exported by platform/index.js'); if (seen[n]) bad.push('exports/' + x.f + ': ' + n + ' is also exported by exports/' + seen[n]); seen[n] = x.f; }));
  const handCss = outside(sheet), seenCss = {};
  css.forEach((x) => { if (handCss.indexOf('"' + x.file + '"') >= 0) bad.push('exports/' + x.f + ': ' + x.file + ' is already imported by platform/platform.css'); if (seenCss[x.file]) bad.push('exports/' + x.f + ': ' + x.file + ' is also imported by exports/' + seenCss[x.file]); seenCss[x.file] = x.f; });
  if (bad.length) throw new Error('platform/exports:\n  ' + bad.join('\n  '));
  const nextIndex = withBlock(index, js.map((x) => x.line), (t, block) => t.replace(/\s*$/, '\n') + block + '\n');
  // before the system rules that come last (steps, nesting, utilities): the parts' stylesheets are component stylesheets
  const nextCss = withBlock(sheet, css.map((x) => x.line), (t, block) => {
    const at = t.indexOf('@import url("system/steps.css")');
    if (at < 0) throw new Error('platform/platform.css: no @import url("system/steps.css") to place the library block before');
    return t.slice(0, at) + block + '\n' + t.slice(at);
  });
  const stale = [];
  if (nextIndex !== index) { stale.push('platform/index.js'); if (!check) fs.writeFileSync(indexFile, nextIndex); }
  if (nextCss !== sheet) { stale.push('platform/platform.css'); if (!check) fs.writeFileSync(cssFile, nextCss); }
  return { stale, exports: js.reduce((n, x) => n + x.names.length, 0), stylesheets: css.length, files: files.length };
};

if (require.main === module) {
  const check = process.argv.includes('--check');
  const r = module.exports(__dirname, { check });
  if (check && r.stale.length) { console.log('Not current (run node build-exports.js): ' + r.stale.join(', ')); process.exit(1); }
  console.log((check ? 'exports ok' : 'Built the library block of platform/index.js and platform/platform.css') + ' (' + r.files + ' part files, ' + r.exports + ' exports, ' + r.stylesheets + ' stylesheets' + (r.stale.length || check ? '' : ', unchanged') + ')');
}
