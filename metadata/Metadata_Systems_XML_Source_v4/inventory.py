def slug(name):
    """Filesystem-safe slug for a system name."""
    import re
    s = name.lower()
    s = re.sub(r'[^a-z0-9]+', '_', s)
    s = s.strip('_')
    return s


def sheet_name(num, name):
    """Excel-safe tab name (max 31 chars)."""
    bad = '/\\?*[]:'
    base = name
    for ch in bad:
        base = base.replace(ch, '-')
    base = base.replace('—', '-').replace('–', '-').replace('/', '-')
    prefix = f"{num:03d}_"
    avail = 31 - len(prefix)
    if len(base) > avail:
        base = base[:avail]
    return prefix + base


